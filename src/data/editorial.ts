import type { Book } from "./types";
export function whyFor(book: Book): string {
  const specific: Record<string, string> = {
    summer:
      "岛上的日子有风、有小小的争执，也有不必说出口的陪伴。它的安静不是空白，而是给生活腾出一点地方。",
    border:
      "渡口的节奏比城市慢一些，感情却并不轻。也许今晚，适合把目光交给一条河。",
    temple:
      "如果有些事情还没想明白，这本书愿意陪你停一停。它不急着安慰你，却认真对待困境。",
    food: "一些草木与吃食，把目光带回手边的生活。今晚可以不必想得很远，先看见眼前的一点好。",
    cities:
      "这些城市没有固定的地图，却有记忆与梦的入口。让想象替你远行一会儿，也许回来时，熟悉的街道会有些不同。",
    rain: "诗里潮湿的街巷，给说不清的情绪留了一个位置。不必立刻知道自己在想什么，先听听文字的回声。",
    winter:
      "这本书会把你带得很远，再用具体的日常把你拉近。辽阔与琐碎同时存在，正好让今晚换一种呼吸。",
    room: "一间房的大小，也牵着一个人能够想象的生活。如果今晚想找一点力量，这份清醒的追问值得一读。",
    metamorphosis:
      "熟悉的日常忽然拐了一个弯。它不太柔软，却可能让你重新看见那些习以为常的关系。",
  };
  if (specific[book.id]) return specific[book.id];
  if (book.tags.includes("科幻"))
    return "把今晚放进一个更大的世界，日常的问题也许会改变形状。这里有陌生的设定，也有熟悉的人的心事。";
  if (book.tags.includes("哲学"))
    return "它给你一个重新提问的角度。与其立刻找到结论，不如先让一个问题陪你多走一段路。";
  if (book.tags.includes("自然"))
    return "文字把视线带到人之外的世界。稍稍改变观察的距离，平常的生活也会显出新的细节。";
  if (book.tags.includes("荒诞"))
    return "故事的路与日常有一点不同。一次小小的偏离，也许刚好能松动今晚习惯的想法。";
  if (book.tags.includes("亲密关系"))
    return "这本书让人与人之间的距离变得可见。那些靠近、误解和重新理解，也许会与你的某个瞬间相遇。";
  return "它把一个人的经验，轻轻放到你的今晚。带走一个细节、一种感受，就已经是一场值得的相遇。";
}
